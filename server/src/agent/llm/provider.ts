import { ChatMessage, ToolDefinition, LLMProvider, LLMResponse, ToolCallRequest } from '../types.js';

/**
 * Google Gemini Provider using native Node fetch
 * Endpoint: https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent
 */
export class GeminiProvider implements LLMProvider {
  name = 'gemini';
  private apiKey: string;
  private model: string;

  constructor(apiKey?: string, model: string = 'gemini-2.0-flash') {
    this.apiKey = apiKey || process.env.GEMINI_API_KEY || '';
    this.model = model;
  }

  async chat(messages: ChatMessage[], tools: ToolDefinition[], stream: boolean = false): Promise<LLMResponse> {
    if (!this.apiKey) {
      throw new Error('GEMINI_API_KEY is not defined in environment variables.');
    }

    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${this.model}:generateContent?key=${this.apiKey}`;

    // Separate system instruction from conversational contents
    let systemInstruction: any = undefined;
    const contents: any[] = [];

    for (const msg of messages) {
      if (msg.role === 'system') {
        systemInstruction = {
          parts: [{ text: msg.content }]
        };
      } else if (msg.role === 'user') {
        contents.push({
          role: 'user',
          parts: [{ text: msg.content }]
        });
      } else if (msg.role === 'assistant') {
        const parts: any[] = [];
        if (msg.content) {
          parts.push({ text: msg.content });
        }
        if (msg.tool_calls && msg.tool_calls.length > 0) {
          for (const tc of msg.tool_calls) {
            let parsedArgs = {};
            try {
              parsedArgs = JSON.parse(tc.function.arguments);
            } catch (e) {
              parsedArgs = {};
            }
            parts.push({
              functionCall: {
                name: tc.function.name,
                args: parsedArgs
              }
            });
          }
        }
        contents.push({ role: 'model', parts });
      } else if (msg.role === 'tool') {
        contents.push({
          role: 'user',
          parts: [{
            functionResponse: {
              name: msg.name || 'tool',
              response: { content: msg.content }
            }
          }]
        });
      }
    }

    // Format tools for Gemini API
    const geminiTools = tools.length > 0 ? [{
      functionDeclarations: tools.map((t) => ({
        name: t.name,
        description: t.description,
        parameters: t.parameters
      }))
    }] : undefined;

    const payload: any = {
      contents,
      generationConfig: {
        temperature: 0.1,
        maxOutputTokens: 2048
      }
    };

    if (systemInstruction) {
      payload.systemInstruction = systemInstruction;
    }
    if (geminiTools) {
      payload.tools = geminiTools;
    }

    const response = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`Gemini API Error [${response.status}]: ${errorText}`);
    }

    const data: any = await response.json();
    const candidate = data.candidates?.[0];
    if (!candidate) {
      return { content: 'No response generated by model.' };
    }

    let textContent = '';
    const toolCalls: ToolCallRequest[] = [];

    const parts = candidate.content?.parts || [];
    for (const part of parts) {
      if (part.text) {
        textContent += part.text;
      }
      if (part.functionCall) {
        toolCalls.push({
          id: `call_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
          name: part.functionCall.name,
          arguments: part.functionCall.args || {}
        });
      }
    }

    return {
      content: textContent,
      toolCalls: toolCalls.length > 0 ? toolCalls : undefined
    };
  }
}

/**
 * xAI Grok Provider using native Node fetch
 * Endpoint: https://api.x.ai/v1/chat/completions
 */
export class GrokProvider implements LLMProvider {
  name = 'grok';
  private apiKey: string;
  private model: string;

  constructor(apiKey?: string, model: string = 'grok-beta') {
    this.apiKey = apiKey || process.env.GROK_API_KEY || '';
    this.model = model;
  }

  async chat(messages: ChatMessage[], tools: ToolDefinition[], stream: boolean = false): Promise<LLMResponse> {
    if (!this.apiKey) {
      throw new Error('GROK_API_KEY is not defined in environment variables.');
    }

    const endpoint = 'https://api.x.ai/v1/chat/completions';

    const formattedMessages = messages.map((m) => {
      const base: any = {
        role: m.role,
        content: m.content
      };
      if (m.name) base.name = m.name;
      if (m.tool_call_id) base.tool_call_id = m.tool_call_id;
      if (m.tool_calls) base.tool_calls = m.tool_calls;
      return base;
    });

    const formattedTools = tools.length > 0 ? tools.map((t) => ({
      type: 'function',
      function: {
        name: t.name,
        description: t.description,
        parameters: t.parameters
      }
    })) : undefined;

    const payload: any = {
      model: this.model,
      messages: formattedMessages,
      temperature: 0.1,
      max_tokens: 2048
    };

    if (formattedTools) {
      payload.tools = formattedTools;
      payload.tool_choice = 'auto';
    }

    const response = await fetch(endpoint, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${this.apiKey}`
      },
      body: JSON.stringify(payload)
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(`Grok API Error [${response.status}]: ${errorText}`);
    }

    const data: any = await response.json();
    const choice = data.choices?.[0];
    const msg = choice?.message;

    let toolCalls: ToolCallRequest[] | undefined = undefined;
    if (msg?.tool_calls && Array.isArray(msg.tool_calls)) {
      toolCalls = msg.tool_calls.map((tc: any) => {
        let args = {};
        try {
          args = JSON.parse(tc.function.arguments);
        } catch (e) {
          args = {};
        }
        return {
          id: tc.id,
          name: tc.function.name,
          arguments: args
        };
      });
    }

    return {
      content: msg?.content || '',
      toolCalls
    };
  }
}

/**
 * Factory to get provider selected by process.env.LLM_PROVIDER
 */
export function getLLMProvider(override?: string): LLMProvider {
  const providerType = (override || process.env.LLM_PROVIDER || 'gemini').toLowerCase();
  if (providerType === 'grok') {
    return new GrokProvider();
  }
  return new GeminiProvider();
}
